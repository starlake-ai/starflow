package ai.starlake.extract

import ai.starlake.config.{DatasetArea, Settings}
import ai.starlake.schema.handlers.{SchemaHandler, StorageHandler}
import ai.starlake.schema.model.{Type, TypesInfo}
import ai.starlake.utils.YamlSerde
import ai.starlake.utils.conversion.BigQueryType
import com.fasterxml.jackson.databind.ObjectMapper
import com.google.cloud.bigquery.{Field, StandardSQLTypeName}
import com.typesafe.scalalogging.LazyLogging
import org.apache.hadoop.fs.Path

import java.util.Locale
import scala.collection.mutable
import scala.util.Try

/** The types of the parameterized BigQuery columns that an extraction meets: `NUMERIC(P, S)`,
  * `BIGNUMERIC(P, S)`, `STRING(L)` and `BYTES(L)` (#1853). Starlake types carry no parameters: a
  * type is generated for each distinct parameter set, such as `numeric_10_2` or `string_10`, from
  * the built-in type of the column, with the zone of its precision and scale and the BigQuery
  * mapping of its parameters, so that the native loads create the same column.
  *
  * A project type of the same name is reused when it has the same primitive type, zone and BigQuery
  * mapping. Otherwise the name gets a suffix.
  *
  * @param projectTypes
  *   the types of the project
  * @param baseType
  *   the type of the project that a built-in type names, from which a type is generated
  */
class BigQueryParameterizedTypes(
  projectTypes: => List[Type],
  baseType: String => Type = BigQueryParameterizedTypes.builtIn
) {

  // The types generated by the extraction, to add to the project, in the order they are met
  private val generated = mutable.LinkedHashMap.empty[String, Type]

  /** @return
    *   the name of the type of a parameterized column, if it is one: the generated type is kept to
    *   be added to the project
    */
  def typeNameOf(field: Field): Option[String] =
    BigQueryParameterizedTypes.typeOf(field, baseType).map { wanted =>
      synchronized {
        val project = projectTypes
        val candidates = Iterator(wanted.name, s"${wanted.name}_extracted") ++
          Iterator.from(2).map(index => s"${wanted.name}_extracted_$index")
        val name = candidates.find { name =>
          generated
            .get(name)
            .orElse(project.find(_.name == name))
            .forall(BigQueryParameterizedTypes.sameType(_, wanted))
        }.get
        if (!generated.contains(name) && !project.exists(_.name == name))
          generated += name -> wanted.copy(name = name)
        name
      }
    }

  /** @return
    *   the generated types that the project does not have yet, which are no longer kept: once added
    *   to the project, they are project types
    */
  def takeNewTypes(): List[Type] = synchronized {
    val types = generated.values.toList
    generated.clear()
    types
  }
}

object BigQueryParameterizedTypes extends LazyLogging {

  def builtIn(name: String): Type =
    SchemaHandler.builtInTypes
      .find(_.name == name)
      .getOrElse(throw new IllegalStateException(s"No built-in type $name"))

  /** @param baseType
    *   the type that a built-in type names, from which a type is generated
    * @return
    *   the type of a parameterized column, named after its parameters, if it is one: a declared
    *   `NUMERIC(38, 9)` is the built-in `decimal`, which creates it
    */
  def typeOf(field: Field, baseType: String => Type = builtIn): Option[Type] = {
    val precision = Option(field.getPrecision).map(_.longValue())
    val scale = Option(field.getScale).map(_.longValue())
    val maxLength = Option(field.getMaxLength).map(_.longValue())
    def decimal(baseName: String, bigQueryName: String): Option[Type] =
      precision
        .filterNot(_ => bigQueryName == "NUMERIC" && precision.contains(38L) && scale.contains(9L))
        .map { p =>
          val parameters = s"$p${scale.map(", " + _).getOrElse("")}"
          parameterized(
            baseType(baseName),
            s"${bigQueryName.toLowerCase(Locale.ROOT)}_$p${scale.map("_" + _).getOrElse("")}",
            s"$bigQueryName($parameters)",
            zone = Some(s"$p,${scale.getOrElse(0L)}")
          )
        }
    Option(field.getType).flatMap(t => Option(t.getStandardType)).flatMap {
      case StandardSQLTypeName.NUMERIC    => decimal("decimal", "NUMERIC")
      case StandardSQLTypeName.BIGNUMERIC => decimal("bignumeric", "BIGNUMERIC")
      case StandardSQLTypeName.STRING =>
        maxLength.map(l => parameterized(baseType("string"), s"string_$l", s"STRING($l)"))
      case StandardSQLTypeName.BYTES =>
        maxLength.map(l => parameterized(baseType("binary"), s"binary_$l", s"BYTES($l)"))
      case _ => None
    }
  }

  /** The built-in type with the BigQuery mapping of the parameters, and for a decimal the zone of
    * its precision and scale. The other engines keep the mapping of the built-in type.
    */
  private def parameterized(
    base: Type,
    name: String,
    bigQueryType: String,
    zone: Option[String] = None
  ): Type =
    base.copy(
      name = name,
      zone = zone.orElse(base.zone),
      sample = None,
      comment = Some(s"BigQuery $bigQueryType, as extract-bq-schema extracted it"),
      ddlMapping = Some(base.ddlMapping.getOrElse(Map.empty) + ("bigquery" -> bigQueryType))
    )

  /** @return
    *   true if two types read and create the same columns: the same primitive type, pattern, zone
    *   and BigQuery type, a NUMERIC(P) being a NUMERIC(P, 0)
    */
  def sameType(a: Type, b: Type): Boolean = {
    def zone(tpe: Type) = tpe.zone.map(_.replaceAll("\\s", ""))
    def bigQuery(tpe: Type) = tpe.getDdlMappingForDB("bigquery").map { mapping =>
      BigQueryType.parse(mapping).map { bigQueryType =>
        if (bigQueryType.precision.isDefined && bigQueryType.scale.isEmpty)
          bigQueryType.copy(scale = Some(0L))
        else bigQueryType
      }
    }
    a.primitiveType == b.primitiveType && a.pattern == b.pattern && zone(a) == zone(b) &&
    bigQuery(a) == bigQuery(b)
  }

  /** @return
    *   true if the BigQuery mapping of the type has parameters: such a type does not replace a
    *   built-in type
    */
  def isParameterized(tpe: Type): Boolean =
    tpe.getDdlMappingForDB("bigquery").flatMap(BigQueryType.parse).exists(_.hasParameters)

  private val json = new ObjectMapper()

  /** @return
    *   the types as items of the YAML list of a types file, not indented
    */
  def yamlItems(types: List[Type]): String = {
    def quoted(value: String) = json.writeValueAsString(value)
    types.map { tpe =>
      val fields = List(
        Some(s"- name: ${quoted(tpe.name)}"),
        Some(s"  primitiveType: ${quoted(tpe.primitiveType.value)}"),
        Some(s"  pattern: ${quoted(tpe.pattern)}"),
        tpe.zone.map(zone => s"  zone: ${quoted(zone)}"),
        tpe.sample.map(sample => s"  sample: ${quoted(sample)}"),
        tpe.comment.map(comment => s"  comment: ${quoted(comment)}"),
        tpe.ddlMapping.filter(_.nonEmpty).map { mapping =>
          ("  ddlMapping:" :: mapping.toList.sortBy(_._1).map { case (engine, ddl) =>
            s"    $engine: ${quoted(ddl)}"
          }).mkString("\n")
        }
      )
      fields.flatten.mkString("", "\n", "\n")
    }.mkString
  }

  /** Adds the types to the `types.sl.yml` file of the project, after its own types, which keep
    * their order: the first type of a primitive type is the one that schema inference uses. The
    * file keeps its text when the types can be appended to it, at the indentation of its items;
    * otherwise it is written again, without its comments, with a `WARN`. A type that the file
    * already has, added by a parallel extraction, is not added again.
    */
  def addToProject(types: List[Type])(implicit settings: Settings): Unit = synchronized {
    implicit val storage: StorageHandler = settings.storageHandler()
    val path = new Path(DatasetArea.types, "types.sl.yml")
    val existing = if (storage.exists(path)) Some(storage.read(path)) else None
    val existingTypes =
      existing.map(YamlSerde.deserializeYamlTypes(_, path.toString)).getOrElse(Nil)
    val (present, added) = types.partition(tpe => existingTypes.exists(_.name == tpe.name))
    present
      .filterNot(tpe => existingTypes.find(_.name == tpe.name).exists(sameType(_, tpe)))
      .foreach { tpe =>
        logger.warn(
          s"The type ${tpe.name} was added to $path by another extraction, with another definition: it is kept"
        )
      }
    if (added.nonEmpty) {
      val items = yamlItems(added)
      def indented(indentation: String) =
        items.linesIterator.map(line => indentation + line).mkString("", "\n", "\n")
      existing match {
        case None =>
          storage.mkdirs(path.getParent)
          storage.write(s"version: 1\ntypes:\n${indented("  ")}", path)
        case Some(text) =>
          val expectedNames = existingTypes.map(_.name) ++ added.map(_.name)
          val appended = """(?m)^([ \t]*)-[ \t]+name[ \t]*:""".r
            .findFirstMatchIn(text)
            .map { item =>
              text + (if (text.endsWith("\n")) "" else "\n") + indented(item.group(1))
            }
            .filter(appended =>
              Try(YamlSerde.deserializeYamlTypes(appended, path.toString)).toOption
                .exists(_.map(_.name) == expectedNames)
            )
          appended match {
            case Some(appended) => storage.write(appended, path)
            case None =>
              logger.warn(
                s"The types extracted could not be appended to the text of $path: it is written again, without its comments"
              )
              YamlSerde.serializeToPath(path, TypesInfo(1, existingTypes ++ added))
          }
      }
      logger.info(
        s"Types of parameterized BigQuery columns added to $path: ${added.map(_.name).mkString(", ")}"
      )
    }
  }
}
